import 'dart:convert';
import 'dart:typed_data';
import 'package:csv/csv.dart';
import 'package:intl/intl.dart';
import '../domain/expense_report_config.dart';

class CsvReportGenerator {
  CsvReportGenerator._();

  static Uint8List generate(ExpenseReportData data) {
    final dateFmt = DateFormat('yyyy-MM-dd HH:mm');
    final shortDateFmt = DateFormat('yyyy-MM-dd');
    final pMap = {for (final p in data.participants) p.id: p};

    final List<List<dynamic>> rows = [];

    // --- Header & Trip Metadata ---
    rows.add(['# COCIRCLE FINANCIAL EXPENSE REPORT']);
    rows.add(['Trip Name', data.tripName]);
    rows.add(['Destination', data.destination ?? 'N/A']);
    rows.add(['Currency', data.currency]);
    rows.add(['Report Type', data.filter.reportType.displayName]);
    rows.add(['Generated At', dateFmt.format(data.generatedAt)]);
    rows.add(['Generated By', data.generatedBy]);
    rows.add(['Total Expenses', data.totalExpenses]);
    rows.add(['Total Contributed', data.totalContributed]);
    rows.add(['Total Outstanding', data.totalOutstanding]);
    rows.add(['Total Participants', data.participants.length]);
    rows.add(['Guest Participants', data.guestCount]);
    rows.add([]); // empty row separator

    // --- Section 1: Expenses ---
    rows.add(['--- SECTION 1: EXPENSE TRANSACTIONS ---']);
    rows.add([
      'Expense ID',
      'Date',
      'Title',
      'Category',
      'Amount',
      'Currency',
      'Payer ID',
      'Payer Name',
      'Split Type',
      'Participants Count',
      'Notes',
    ]);

    for (final exp in data.expenses) {
      final payerName = pMap[exp.payerId]?.name ?? exp.payerId;
      rows.add([
        exp.id,
        shortDateFmt.format(exp.date),
        exp.title,
        exp.category,
        exp.amount,
        data.currency,
        exp.payerId,
        payerName,
        exp.splitType.name,
        exp.splitDetails.length,
        exp.notes ?? '',
      ]);
    }
    rows.add([]);

    // --- Section 2: Detailed Expense Splits ---
    rows.add(['--- SECTION 2: PARTICIPANT EXPENSE SPLITS ---']);
    rows.add([
      'Expense ID',
      'Expense Title',
      'Total Amount',
      'Participant ID',
      'Participant Name',
      'Participant Type',
      'Share Amount',
    ]);

    for (final exp in data.expenses) {
      for (final entry in exp.splitDetails.entries) {
        final p = pMap[entry.key];
        rows.add([
          exp.id,
          exp.title,
          exp.amount,
          entry.key,
          p?.name ?? entry.key,
          p?.isGuest == true ? 'Guest' : 'Registered Member',
          entry.value,
        ]);
      }
    }
    rows.add([]);

    // --- Section 3: Participant Balances ---
    rows.add(['--- SECTION 3: PARTICIPANT BALANCES & SETTLEMENT STATUS ---']);
    rows.add([
      'Participant ID',
      'Name',
      'Type',
      'Total Paid',
      'Total Share',
      'Net Balance',
      'Status',
    ]);

    for (final p in data.participants) {
      final b = data.balances[p.id];
      final paid = b?.totalPaidAmount ?? 0.0;
      final share = b?.totalShareAmount ?? 0.0;
      final net = b?.netAmount ?? 0.0;
      final status = (b?.netPaise ?? 0) == 0
          ? 'Settled'
          : (net > 0 ? 'To Receive' : 'To Pay');

      rows.add([
        p.id,
        p.name,
        p.isGuest ? 'Guest' : 'Registered Member',
        paid,
        share,
        net,
        status,
      ]);
    }
    rows.add([]);

    // --- Section 4: Payments & Contributions ---
    if (data.filter.includePayments && data.payments.isNotEmpty) {
      rows.add(['--- SECTION 4: PAYMENTS & CONTRIBUTIONS ---']);
      rows.add([
        'Payment ID',
        'Date',
        'From Member ID',
        'From Member Name',
        'To Member ID',
        'To Member Name',
        'Amount',
        'Method',
        'Status',
        'Reference Number',
        'Recorded On Behalf Of Guest',
        'Notes',
      ]);

      for (final pay in data.payments) {
        rows.add([
          pay.id,
          shortDateFmt.format(pay.paymentDate),
          pay.fromMemberId,
          pMap[pay.fromMemberId]?.name ?? pay.fromMemberId,
          pay.toMemberId,
          pMap[pay.toMemberId]?.name ?? pay.toMemberId,
          pay.amount,
          pay.paymentMethod,
          pay.paymentStatus,
          pay.referenceNumber ?? '',
          pay.recordedOnBehalfOfGuest ? 'YES' : 'NO',
          pay.notes ?? '',
        ]);
      }
      rows.add([]);
    }

    // --- Section 5: Multilateral Settlement Transfers ---
    if (data.filter.includeSettlements && data.optimizedSettlements.isNotEmpty) {
      rows.add(['--- SECTION 5: RECOMMENDED SETTLEMENT TRANSFERS ---']);
      rows.add([
        'From Member ID',
        'From Member Name',
        'To Member ID',
        'To Member Name',
        'Transfer Amount',
        'Currency',
      ]);

      for (final st in data.optimizedSettlements) {
        rows.add([
          st.fromUid,
          pMap[st.fromUid]?.name ?? st.fromUid,
          st.toUid,
          pMap[st.toUid]?.name ?? st.toUid,
          st.amount,
          data.currency,
        ]);
      }
      rows.add([]);
    }

    // --- Section 6: Adjustments & Write-offs ---
    if (data.filter.includeAdjustments && data.adjustments.isNotEmpty) {
      rows.add(['--- SECTION 6: VOLUNTARY ADJUSTMENTS & WRITE-OFFS ---']);
      rows.add([
        'Adjustment ID',
        'Type',
        'Amount',
        'Creditor (Waived By)',
        'Debtor (Beneficiary)',
        'Reason',
        'Date',
      ]);

      for (final adj in data.adjustments) {
        rows.add([
          adj.id,
          'Debt Waiver',
          adj.amount,
          pMap[adj.creditorUid]?.name ?? adj.creditorUid,
          pMap[adj.debtorUid]?.name ?? adj.debtorUid,
          adj.reason,
          shortDateFmt.format(adj.createdAt),
        ]);
      }
      rows.add([]);
    }

    final csvString = csv.encode(rows);
    return Uint8List.fromList(utf8.encode(csvString));
  }
}

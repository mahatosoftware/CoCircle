import 'dart:typed_data';
import 'package:excel/excel.dart';
import 'package:intl/intl.dart';
import '../domain/expense_report_config.dart';

class ExcelReportGenerator {
  ExcelReportGenerator._();

  static Uint8List generate(ExpenseReportData data) {
    final excel = Excel.createExcel();
    final dateFmt = DateFormat('yyyy-MM-dd HH:mm');
    final shortDateFmt = DateFormat('yyyy-MM-dd');
    final pMap = {for (final p in data.participants) p.id: p};

    CellValue? toCell(dynamic val) {
      if (val == null) return null;
      if (val is int) return IntCellValue(val);
      if (val is double) return DoubleCellValue(val);
      if (val is bool) return BoolCellValue(val);
      if (val is DateTime) {
        return DateTimeCellValue(
          year: val.year,
          month: val.month,
          day: val.day,
          hour: val.hour,
          minute: val.minute,
          second: val.second,
        );
      }
      return TextCellValue(val.toString());
    }

    void append(Sheet sheet, List<dynamic> items) {
      sheet.appendRow(items.map((i) => toCell(i)).toList());
    }

    // ==========================================
    // SHEET 1: TRIP SUMMARY
    // ==========================================
    final summarySheet = excel['Trip Summary'];
    append(summarySheet, ['COCIRCLE TRIP FINANCIAL SUMMARY']);
    append(summarySheet, []);
    append(summarySheet, ['Trip Name', data.tripName]);
    append(summarySheet, ['Destination', data.destination ?? 'Not specified']);
    append(summarySheet, ['Currency', data.currency]);
    append(summarySheet, ['Report Generated', dateFmt.format(data.generatedAt)]);
    append(summarySheet, ['Generated By', data.generatedBy]);
    append(summarySheet, ['Report Scope', data.filter.reportType.displayName]);
    append(summarySheet, []);

    append(summarySheet, ['KEY FINANCIAL METRICS']);
    append(summarySheet, ['Total Expenditure', data.totalExpenses]);
    append(summarySheet, ['Total Contributions Paid', data.totalContributed]);
    append(summarySheet, ['Total Outstanding Owed', data.totalOutstanding]);
    append(summarySheet, ['Average Expense Per Person', data.averagePerParticipant]);
    append(summarySheet, ['Total Participants', data.participants.length]);
    append(summarySheet, ['Registered Members', data.registeredCount]);
    append(summarySheet, ['Guest Participants', data.guestCount]);
    append(summarySheet, []);

    append(summarySheet, ['EXPENSE CATEGORY BREAKDOWN']);
    append(summarySheet, ['Category', 'Total Amount', 'Expenses Count', '% of Total']);
    for (final entry in data.categoryTotals.entries) {
      final pct = data.totalExpenses > 0 ? (entry.value / data.totalExpenses) * 100 : 0.0;
      append(summarySheet, [
        entry.key,
        entry.value,
        data.categoryCounts[entry.key] ?? 0,
        double.parse(pct.toStringAsFixed(1)),
      ]);
    }

    // ==========================================
    // SHEET 2: ALL EXPENSES
    // ==========================================
    final expensesSheet = excel['All Expenses'];
    append(expensesSheet, [
      'Expense ID',
      'Date',
      'Description / Title',
      'Category',
      'Amount (${data.currency})',
      'Payer ID',
      'Payer Name',
      'Split Method',
      'Participants Count',
      'Notes',
    ]);

    for (final e in data.expenses) {
      append(expensesSheet, [
        e.id,
        shortDateFmt.format(e.date),
        e.title,
        e.category,
        e.amount,
        e.payerId,
        pMap[e.payerId]?.name ?? e.payerId,
        e.splitType.name,
        e.splitDetails.length,
        e.notes ?? '',
      ]);
    }

    // ==========================================
    // SHEET 3: EXPENSE SPLITS
    // ==========================================
    final splitsSheet = excel['Expense Splits'];
    append(splitsSheet, [
      'Expense ID',
      'Expense Title',
      'Total Amount',
      'Participant ID',
      'Participant Name',
      'Participant Type',
      'Share Amount (${data.currency})',
    ]);

    for (final e in data.expenses) {
      for (final entry in e.splitDetails.entries) {
        final p = pMap[entry.key];
        append(splitsSheet, [
          e.id,
          e.title,
          e.amount,
          entry.key,
          p?.name ?? entry.key,
          p?.isGuest == true ? 'Guest' : 'Member',
          entry.value,
        ]);
      }
    }

    // ==========================================
    // SHEET 4: PARTICIPANTS
    // ==========================================
    final participantsSheet = excel['Participant Summary'];
    append(participantsSheet, [
      'Participant ID',
      'Name',
      'Type',
      'Total Paid (${data.currency})',
      'Total Share (${data.currency})',
      'Net Balance (${data.currency})',
      'Settlement Status',
    ]);

    for (final p in data.participants) {
      final b = data.balances[p.id];
      final paid = b?.totalPaidAmount ?? 0.0;
      final share = b?.totalShareAmount ?? 0.0;
      final net = b?.netAmount ?? 0.0;
      final isSettled = (b?.netPaise ?? 0) == 0;
      final status = isSettled ? 'Settled' : (net > 0 ? 'To Receive' : 'To Pay');

      append(participantsSheet, [
        p.id,
        p.name,
        p.isGuest ? 'Guest Participant' : 'Registered Member',
        paid,
        share,
        net,
        status,
      ]);
    }

    // ==========================================
    // SHEET 5: PAYMENTS
    // ==========================================
    final paymentsSheet = excel['Payments'];
    append(paymentsSheet, [
      'Payment ID',
      'Date',
      'From ID',
      'From Name',
      'To ID',
      'To Name',
      'Amount (${data.currency})',
      'Payment Method',
      'Status',
      'Reference Number',
      'On Behalf of Guest',
      'Notes',
    ]);

    for (final pay in data.payments) {
      append(paymentsSheet, [
        pay.id,
        shortDateFmt.format(pay.paymentDate),
        pay.fromMemberId,
        pMap[pay.fromMemberId]?.name ?? pay.fromMemberId,
        pay.toMemberId,
        pMap[pay.toMemberId]?.name ?? pay.toMemberId,
        pay.amount,
        pay.paymentMethod,
        pay.paymentStatus,
        pay.referenceNumber ?? '',
        pay.recordedOnBehalfOfGuest ? 'YES' : 'NO',
        pay.notes ?? '',
      ]);
    }

    // ==========================================
    // SHEET 6: SETTLEMENT DETAILS
    // ==========================================
    final settlementSheet = excel['Settlement Details'];
    append(settlementSheet, [
      'Transfer From (Debtor)',
      'Transfer To (Creditor)',
      'Amount (${data.currency})',
      'Settlement Method',
      'Status',
    ]);

    for (final st in data.optimizedSettlements) {
      append(settlementSheet, [
        pMap[st.fromUid]?.name ?? st.fromUid,
        pMap[st.toUid]?.name ?? st.toUid,
        st.amount,
        'Optimal Direct Settlement',
        'Recommended',
      ]);
    }

    // ==========================================
    // SHEET 7: OUTSTANDING BALANCES
    // ==========================================
    final outstandingSheet = excel['Outstanding Balances'];
    append(outstandingSheet, [
      'Participant Name',
      'Participant Type',
      'Amount Owed (${data.currency})',
      'Amount to Receive (${data.currency})',
      'Status',
    ]);

    for (final p in data.participants) {
      final b = data.balances[p.id];
      if (b != null && !b.isSettled) {
        append(outstandingSheet, [
          p.name,
          p.isGuest ? 'Guest' : 'Member',
          b.amountOwed,
          b.amountToReceive,
          b.owes ? 'Pending Payment' : 'Pending Receipt',
        ]);
      }
    }

    // ==========================================
    // SHEET 8: ADJUSTMENTS AND WRITE-OFFS
    // ==========================================
    final adjustmentsSheet = excel['Adjustments & Write-offs'];
    append(adjustmentsSheet, [
      'Adjustment ID',
      'Type',
      'Amount (${data.currency})',
      'Creditor (Waived By)',
      'Debtor (Beneficiary)',
      'Reason',
      'Date',
    ]);

    for (final adj in data.adjustments) {
      append(adjustmentsSheet, [
        adj.id,
        'Debt Waiver',
        adj.amount,
        pMap[adj.creditorUid]?.name ?? adj.creditorUid,
        pMap[adj.debtorUid]?.name ?? adj.debtorUid,
        adj.reason,
        shortDateFmt.format(adj.createdAt),
      ]);
    }

    // Remove default Sheet1 created by Excel
    excel.delete('Sheet1');
    excel.setDefaultSheet('Trip Summary');

    final fileBytes = excel.save();
    return Uint8List.fromList(fileBytes ?? []);
  }
}
